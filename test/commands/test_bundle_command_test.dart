import 'dart:convert';
import 'dart:io';

import 'package:dowel/dowel.dart';
import 'package:dowel/src/commands/test_bundle_command.dart';
import 'package:path/path.dart' as p;
import 'package:test/test.dart';

/// A test file body with a single synchronous `main` and [filler] comment
/// lines, so its weight (line count) is `filler + 2` plus [extra] lines.
String _testSource({int filler = 0, String extra = ''}) {
  final buffer = StringBuffer(extra)..writeln('void main() {');
  for (var i = 0; i < filler; i++) {
    buffer.writeln('  // filler $i');
  }
  buffer.writeln('}');
  return buffer.toString();
}

void main() {
  group('TestBundleCommand', () {
    final command = TestBundleCommand();

    test('metadata: name=test:bundle, boot=none', () {
      expect(command.name, 'test:bundle');
      expect(command.boot, CommandBoot.none);
      expect(command.description, isNotEmpty);
    });

    test('declares --shards with a default of 3 and --only', () {
      final options = command.parsedSignature!.options;

      expect(
        options.map((option) => option.name),
        containsAll(<String>['shards', 'only']),
      );
      expect(
        options.firstWhere((option) => option.name == 'shards').defaultValue,
        '3',
      );
    });
  });

  group('TestBundleCommand.handle()', () {
    late Directory project;
    late Directory testDir;
    late BufferedOutput output;

    setUp(() {
      project = Directory.systemTemp.createTempSync('test_bundle_');
      File(p.join(project.path, 'pubspec.yaml'))
          .writeAsStringSync('name: probe\n');
      testDir = Directory(p.join(project.path, 'test'))..createSync();
      output = BufferedOutput();
    });

    tearDown(() {
      if (project.existsSync()) project.deleteSync(recursive: true);
    });

    void seed(String relative, String source) {
      File(p.join(testDir.path, relative))
        ..parent.createSync(recursive: true)
        ..writeAsStringSync(source);
    }

    Future<int> bundle([Map<String, dynamic> options = const {}]) {
      return TestBundleCommand(projectRoot: project.path)
          .handle(DowelContext.bare(MapInput(options), output));
    }

    /// Bundle file names in `test/`, sorted.
    List<String> bundles() {
      return testDir
          .listSync()
          .whereType<File>()
          .map((file) => p.basename(file.path))
          .where((name) => name.startsWith('bundle'))
          .toList()
        ..sort();
    }

    String read(String name) =>
        File(p.join(testDir.path, name)).readAsStringSync();

    /// The relative paths an entry imports, in import order.
    List<String> members(String name) {
      return RegExp(r"^import '([^']+)'", multiLine: true)
          .allMatches(read(name))
          .map((match) => match.group(1)!)
          .where((path) => !path.startsWith('package:'))
          .toList();
    }

    test('writes the generated entry shape for a single file', () async {
      seed('widget_test.dart', _testSource());

      final code = await bundle();

      expect(code, 0);
      expect(bundles(), <String>['bundle_0.g.dart']);
      expect(
        read('bundle_0.g.dart'),
        '// dart format width=80\n'
        '// GENERATED by dowel test:bundle; do not edit, do not commit.\n'
        "import 'package:flutter_test/flutter_test.dart';\n"
        '\n'
        "import 'widget_test.dart' as t0;\n"
        '\n'
        'void main() {\n'
        "  group('widget_test.dart', t0.main);\n"
        '}\n',
      );
    });

    test('lays out a long path the way dart format does', () async {
      const path =
          'app/some/really/long/directory/name/that/keeps/going_and_going_test.dart';
      seed(path, _testSource());

      expect(await bundle(), 0);

      expect(
        read('bundle_0.g.dart'),
        '// dart format width=80\n'
        '// GENERATED by dowel test:bundle; do not edit, do not commit.\n'
        "import 'package:flutter_test/flutter_test.dart';\n"
        '\n'
        "import '$path'\n"
        '    as t0;\n'
        '\n'
        'void main() {\n'
        '  group(\n'
        "    '$path',\n"
        '    t0.main,\n'
        '  );\n'
        '}\n',
      );
    });

    test(
      'deals heaviest first onto the lightest shard, ties by path',
      () async {
        seed('a_test.dart', _testSource(filler: 8));
        seed('c_test.dart', _testSource(filler: 3));
        seed('b_test.dart', _testSource(filler: 3));
        seed('d_test.dart', _testSource(filler: 1));

        expect(await bundle(<String, dynamic>{'shards': '2'}), 0);

        // a (10) -> 0; b (5) -> 1; c (5) -> 1; d (3) -> 0 (10 against 10).
        expect(bundles(), <String>['bundle_0.g.dart', 'bundle_1.g.dart']);
        expect(members('bundle_0.g.dart'), <String>[
          'a_test.dart',
          'd_test.dart',
        ]);
        expect(members('bundle_1.g.dart'), <String>[
          'b_test.dart',
          'c_test.dart',
        ]);
      },
    );

    test(
      'sorts the members of an entry by path, not by dealing order',
      () async {
        seed('z_test.dart', _testSource(filler: 10));
        seed('m_test.dart', _testSource(filler: 4));
        seed('a/b_test.dart', _testSource(filler: 1));

        expect(await bundle(<String, dynamic>{'shards': '2'}), 0);

        // z -> 0; m -> 1; a/b -> 1, dealt after m but sorted before it.
        expect(members('bundle_0.g.dart'), <String>['z_test.dart']);
        expect(members('bundle_1.g.dart'), <String>[
          'a/b_test.dart',
          'm_test.dart',
        ]);
        expect(
          read('bundle_1.g.dart'),
          contains(
            "  group('a/b_test.dart', t0.main);\n"
            "  group('m_test.dart', t1.main);\n",
          ),
        );
      },
    );

    test('caps --shards at the number of eligible files', () async {
      seed('a_test.dart', _testSource());
      seed('b_test.dart', _testSource());

      expect(await bundle(<String, dynamic>{'shards': '5'}), 0);

      expect(bundles(), <String>['bundle_0.g.dart', 'bundle_1.g.dart']);
    });

    test('puts a `// shard: alone` file in bundle_alone.g.dart', () async {
      seed('a_test.dart', _testSource());
      seed('b_test.dart', _testSource());
      seed('latency_test.dart', _testSource(extra: '// shard: alone\n'));

      expect(await bundle(), 0);

      // Two files left to deal, so the default 3 shards become 2.
      expect(bundles(), <String>[
        'bundle_0.g.dart',
        'bundle_1.g.dart',
        'bundle_alone.g.dart',
      ]);
      expect(members('bundle_alone.g.dart'), <String>['latency_test.dart']);
      expect(members('bundle_0.g.dart'), isNot(contains('latency_test.dart')));
      expect(members('bundle_1.g.dart'), isNot(contains('latency_test.dart')));
    });

    test('the alone marker must be the whole line', () async {
      seed('a_test.dart', _testSource(extra: '// shard: alone, maybe\n'));

      expect(await bundle(), 0);

      expect(bundles(), <String>['bundle_0.g.dart']);
    });

    test('refuses a tree where every file is marked alone', () async {
      seed('a_test.dart', _testSource(extra: '// shard: alone\n'));

      expect(await bundle(), 1);

      expect(output.content, contains('every test file is marked'));
      expect(bundles(), isEmpty);
    });

    test('refuses a tree without any *_test.dart', () async {
      expect(await bundle(), 1);

      expect(output.content, contains('no *_test.dart under test/'));
    });

    test('breaks a weight tie by path, lowest path first', () async {
      seed('c_test.dart', _testSource(filler: 4));
      seed('b_test.dart', _testSource(filler: 4));

      expect(await bundle(<String, dynamic>{'shards': '2'}), 0);

      // Equal weights: b is dealt first and takes the first shard.
      expect(members('bundle_0.g.dart'), <String>['b_test.dart']);
      expect(members('bundle_1.g.dart'), <String>['c_test.dart']);
    });

    test('weighs a file without a trailing newline as one line', () async {
      seed('a_test.dart', 'void main() {}');
      seed('b_test.dart', 'void main() {}');

      expect(await bundle(<String, dynamic>{'shards': '2'}), 0);

      // A weight of zero would drop both onto the first shard and leave the
      // second one empty, which `flutter test` rejects.
      expect(members('bundle_0.g.dart'), <String>['a_test.dart']);
      expect(members('bundle_1.g.dart'), <String>['b_test.dart']);
    });

    test(
      'bundles a file that is not valid UTF-8 instead of crashing',
      () async {
        File(p.join(testDir.path, 'a_test.dart')).writeAsBytesSync(<int>[
          ...utf8.encode('void main() {\n}\n// '),
          0xff,
          0x0a,
        ]);

        expect(await bundle(), 0);
        expect(members('bundle_0.g.dart'), <String>['a_test.dart']);
      },
    );

    test('removes what it staged when a later write fails', () async {
      seed('a_test.dart', _testSource(filler: 4));
      seed('b_test.dart', _testSource(filler: 4));
      seed('bundle_0.g.dart', 'earlier');
      Directory(p.join(testDir.path, 'bundle_1.g.dart.tmp')).createSync();

      await expectLater(
        bundle(<String, dynamic>{'shards': '2'}),
        throwsA(isA<FileSystemException>()),
      );

      expect(
        File(p.join(testDir.path, 'bundle_0.g.dart.tmp')).existsSync(),
        isFalse,
      );
      expect(read('bundle_0.g.dart'), 'earlier');
    });

    test('removes stale bundles and leaves no staged file behind', () async {
      seed('a_test.dart', _testSource());
      seed('bundle_7.g.dart', 'stale');
      seed('bundle_alone.g.dart', 'stale');

      expect(await bundle(), 0);

      expect(
        testDir.listSync().map((entity) => p.basename(entity.path)).toList()
          ..sort(),
        <String>['a_test.dart', 'bundle_0.g.dart'],
      );
    });

    for (final shards in <String>['0', '-1', 'abc', '', '2.5']) {
      test('refuses --shards=$shards and writes nothing', () async {
        seed('a_test.dart', _testSource());

        expect(await bundle(<String, dynamic>{'shards': shards}), 1);

        expect(output.content, contains('--shards takes a positive integer'));
        expect(bundles(), isEmpty);
      });
    }

    group('refusals', () {
      test('names every offending file and writes nothing', () async {
        seed('good_test.dart', _testSource());
        seed('async_test.dart', 'void main() async {\n}\n');
        seed(
          'tagged_test.dart',
          _testSource(extra: "@Tags(['slow'])\nlibrary;\n"),
        );
        seed('bundle_0.g.dart', 'stale');

        expect(await bundle(), 1);

        expect(output.content, contains('test/async_test.dart'));
        expect(output.content, contains('test/tagged_test.dart'));
        expect(output.content, isNot(contains('test/good_test.dart')));
        expect(output.content, contains('nothing written'));
        expect(bundles(), <String>['bundle_0.g.dart']);
        expect(read('bundle_0.g.dart'), 'stale');
      });

      test('a path with a character outside [A-Za-z0-9_./-]', () async {
        seed('my widget_test.dart', _testSource());

        expect(await bundle(), 1);

        expect(
          output.content,
          contains(
            "test/my widget_test.dart has a character outside [A-Za-z0-9_./-]",
          ),
        );
      });

      for (final annotation in <String>[
        "@TestOn('vm')",
        "@Tags(['slow'])",
        '@Timeout(Duration(seconds: 5))',
        "@Skip('later')",
        '@Retry(2)',
        "@OnPlatform({'windows': Skip()})",
      ]) {
        final name = annotation.substring(1, annotation.indexOf('('));

        test('a library annotation: @$name', () async {
          seed('a_test.dart', _testSource(extra: '$annotation\nlibrary;\n\n'));

          expect(await bundle(), 1);

          expect(
            output.content,
            contains('test/a_test.dart carries @$name, a library annotation'),
          );
        });
      }

      test('an annotation below a licence header is still refused', () async {
        seed(
          'a_test.dart',
          _testSource(
            extra:
                "// Copyright 2026\n// Licensed under MIT\n@TestOn('vm')\n"
                'library;\n\n',
          ),
        );

        expect(await bundle(), 1);

        expect(output.content, contains('a library annotation'));
      });

      test('an indented annotation is not a library annotation', () async {
        seed('a_test.dart', _testSource(extra: "  @Tags(['x'])\n"));

        expect(await bundle(), 0);
      });

      for (final entry in <String, String>{
        'void main() async': 'void main() async {\n}\n',
        'two mains': 'void main() {\n}\nvoid main() {\n}\n',
        'no main': '// nothing here\n',
        'an arrow main': 'void main() => group("x", () {});\n',
      }.entries) {
        test('a main other than one `void main() {`: ${entry.key}', () async {
          seed('a_test.dart', entry.value);

          expect(await bundle(), 1);

          expect(
            output.content,
            contains("test/a_test.dart has no single 'void main() {'"),
          );
        });
      }

      for (final signature in <String>[
        'Future<void> main() async {',
        'FutureOr<void> main() {',
      ]) {
        test('an asynchronous main is named: $signature', () async {
          seed('a_test.dart', '$signature\n}\n');

          expect(await bundle(), 1);

          final declared = signature.substring(0, signature.indexOf(' main'));
          expect(
            output.content,
            contains('test/a_test.dart declares `$declared main`'),
          );
        });
      }

      test('a flutter_test_config.dart below test/', () async {
        seed('a_test.dart', _testSource());
        seed('widgets/flutter_test_config.dart', 'void testExecutable() {}\n');

        expect(await bundle(), 1);

        expect(
          output.content,
          contains('test/widgets/flutter_test_config.dart'),
        );
        expect(output.content, contains('upwards'));
        expect(bundles(), isEmpty);
      });

      test('allows test/flutter_test_config.dart itself', () async {
        seed('a_test.dart', _testSource());
        seed('flutter_test_config.dart', 'void testExecutable() {}\n');

        expect(await bundle(), 0);
      });
    });

    group('--only', () {
      late File list;

      setUp(() {
        list = File(p.join(project.path, 'only.txt'));
      });

      test('bundles only the listed files, blank lines ignored', () async {
        seed('a_test.dart', _testSource());
        seed('b_test.dart', _testSource());
        seed('c/d_test.dart', _testSource());
        list.writeAsStringSync('test/c/d_test.dart\n\n   \ntest/a_test.dart\n');

        expect(await bundle(<String, dynamic>{'only': list.path}), 0);

        expect(bundles(), <String>['bundle_0.g.dart', 'bundle_1.g.dart']);
        expect(
          <String>[...members('bundle_0.g.dart'), ...members('bundle_1.g.dart')]
            ..sort(),
          <String>['a_test.dart', 'c/d_test.dart'],
        );
      });

      test('a subset of alone files writes no shard', () async {
        seed('a_test.dart', _testSource());
        seed('latency_test.dart', _testSource(extra: '// shard: alone\n'));
        list.writeAsStringSync('test/latency_test.dart\n');

        expect(await bundle(<String, dynamic>{'only': list.path}), 0);

        expect(bundles(), <String>['bundle_alone.g.dart']);
      });

      test('an empty list clears stale bundles and writes none', () async {
        seed('a_test.dart', _testSource());
        seed('bundle_0.g.dart', 'stale');
        list.writeAsStringSync('\n');

        expect(await bundle(<String, dynamic>{'only': list.path}), 0);

        expect(output.content, contains('no bundle written'));
        expect(bundles(), isEmpty);
      });

      test('refuses every bad path by its rule and writes nothing', () async {
        seed('a_test.dart', _testSource());
        seed('helper.dart', 'void helper() {}\n');
        seed('bundle_0.g.dart', 'stale');
        list.writeAsStringSync(
          'test/../a_test.dart\n'
          'test/./a_test.dart\n'
          './test/a_test.dart\n'
          'lib/a_test.dart\n'
          'test/missing_test.dart\n'
          'test/helper.dart\n',
        );

        expect(await bundle(<String, dynamic>{'only': list.path}), 1);

        final out = output.content;
        expect(out, contains('test/../a_test.dart is not under test/'));
        expect(out, contains('test/./a_test.dart is not under test/'));
        expect(out, contains('./test/a_test.dart is not under test/'));
        expect(out, contains('lib/a_test.dart is not under test/'));
        expect(out, contains('test/missing_test.dart does not exist'));
        expect(out, contains('test/helper.dart does not end in _test.dart'));
        expect(read('bundle_0.g.dart'), 'stale');
      });

      test('refuses a path listed twice', () async {
        seed('a_test.dart', _testSource());
        seed('b_test.dart', _testSource());
        list.writeAsStringSync(
          'test/a_test.dart\ntest/b_test.dart\ntest/a_test.dart\n',
        );

        expect(await bundle(<String, dynamic>{'only': list.path}), 1);

        expect(output.content, contains('listed twice: test/a_test.dart'));
        expect(bundles(), isEmpty);
      });

      test('listed files meet the same refusals', () async {
        seed('a_test.dart', 'void main() async {\n}\n');
        list.writeAsStringSync('test/a_test.dart\n');

        expect(await bundle(<String, dynamic>{'only': list.path}), 1);

        expect(
          output.content,
          contains("test/a_test.dart has no single 'void main() {'"),
        );
      });

      test('refuses a list file that cannot be read', () async {
        expect(
          await bundle(<String, dynamic>{
            'only': p.join(project.path, 'missing.txt'),
          }),
          1,
        );

        expect(output.content, contains('is not readable'));
      });
    });
  });
}
