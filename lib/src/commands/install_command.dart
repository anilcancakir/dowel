/// `install` — scaffold the canonical native Flutter consumer
/// (`bin/dispatcher.dart` + `lib/app/_plugins.g.dart` + initial
/// `lib/app/commands/_index.g.dart`) into the current project AND
/// auto-chain `make:fast-cli` so `bin/dowel` lands in the same invocation.
///
/// Idempotent: skips files that already exist; pass `--force` to
/// overwrite.
///
/// Magic-installed consumers reach the same canonical state by routing
/// `magic:install` through this command in-process. Vanilla Flutter
/// consumers use `dart run dowel install` directly.
final class InstallDowelCommand extends DowelCommand {
  @override
  String get signature => 'install '
      '{--force : Overwrite files even when they already exist}';

  @override
  String get description =>
      'Scaffold the canonical Flutter consumer (bin/dispatcher.dart + barrels) '
      'and install bin/dowel fast-CLI.';

  @override
  CommandBoot get boot => CommandBoot.none;

  @override
  Future<int> handle(DowelContext ctx) async {
    final force = ctx.input.option('force') as bool? ?? false;
    final root = FileHelper.findProjectRoot();
    return scaffoldInto(root: root, force: force, ctx: ctx);
  }

  /// Public composition seam. Writes the 3 canonical files into [root],
  /// injects the `dowel` pubspec dep (path-dep when package_config resolves
  /// it locally, `^<dowelVersion>` otherwise), then chains to
  /// `MakeFastCliCommand.scaffoldInto` so `bin/dowel` + `.gitignore` + AOT
  /// bundle land in the same invocation. A project still holding the files
  /// fluttersdk_artisan generated gets the migration steps and exit 1 instead,
  /// unless [force] overwrites them.
  ///
  /// Idempotent across all phases:
  /// - Each of the 3 file writes skips when the target already exists unless
  ///   [force] is true.
  /// - Pubspec dep injection is a no-op when `dowel` is already listed
  ///   under `dependencies:` or `dev_dependencies:`, whatever its constraint.
  /// - The auto-chained `MakeFastCliCommand.scaffoldInto` is itself
  ///   idempotent (per its docblock).
  ///
  /// Called by both the `install` CLI entry (via [handle]) and by
  /// `MagicInstallDowelCommand.delegateDowelInstall` (cross-package composition
  /// in the magic-managed install flow). The previous `@visibleForTesting`
  /// gate was lifted, mirroring `MakeFastCliCommand.scaffoldInto`, so
  /// cross-command production composition does not trip
  /// `invalid_use_of_visible_for_testing_member`.
  ///
  /// Returns 0 on success, 1 on missing pubspec name, and propagates any
  /// non-zero exit from the auto-chained `MakeFastCliCommand`.
  static Future<int> scaffoldInto({
    required String root,
    required bool force,
    required DowelContext ctx,
  }) async {
    // 1. Read consumer name from pubspec.yaml. Without it the stub cannot
    //    substitute the `{{ name }}` placeholder for the two `package:` imports
    //    that wire the codegen barrels into the dispatcher.
    final consumerName = _readConsumerName(root);
    if (consumerName == null) {
      ctx.output.error(
        'Could not read `name:` from $root/pubspec.yaml. '
        'Run `install` from a Dart/Flutter project root.',
      );
      return 1;
    }

    // 1a. A project migrating from fluttersdk_artisan keeps the generated
    //     files that package wrote. Each would be skipped as existing, and the
    //     auto-chained build would then fail on their imports, so stop and say
    //     what to delete instead. --force overwrites them, as it always has.
    final stale = staleGeneratedFiles(root);
    if (stale.isNotEmpty && !force) {
      ctx.output.error(artisanMigrationSteps(artisanLeftovers(root)));
      return 1;
    }

    var wrote = 0;
    var skipped = 0;

    // 2. bin/dispatcher.dart — canonical consumer wrapper rendered from the
    //    `dispatcher.dart.stub` template with the consumer package name.
    final dispatcherPath = p.join(root, 'bin', 'dispatcher.dart');
    if (_shouldWrite(dispatcherPath, force)) {
      final raw = StubLoader.load('dispatcher.dart');
      final rendered = StubLoader.replace(raw, {'name': consumerName});
      FileHelper.writeFile(dispatcherPath, rendered);
      ctx.output.success('Created: $dispatcherPath');
      wrote++;
    } else {
      ctx.output.info('Skipped (exists): $dispatcherPath');
      skipped++;
    }

    // 3. lib/app/_plugins.g.dart — initial empty barrel for the plugin
    //    provider list. Regenerated by `plugin:install` / `plugins:refresh`.
    //
    //    When `.dowel/plugins.json` already exists (re-running `install` on
    //    a project that previously enrolled plugins), the empty initial stub
    //    would silently stomp the canonical barrel. We always materialise the
    //    initial stub first so a fresh consumer ends with a valid file, then
    //    auto-trigger `plugins:refresh` to regenerate from `plugins.json` in
    //    the populated case. `PluginsRefreshCommand` writes atomically via
    //    `.tmp` + rename, so the empty intermediate state is never observed
    //    by readers.
    final pluginsGPath = p.join(root, 'lib', 'app', '_plugins.g.dart');
    if (_shouldWrite(pluginsGPath, force)) {
      final raw = StubLoader.load('consumer_plugins_g.dart');
      FileHelper.writeFile(pluginsGPath, raw);
      ctx.output.success('Created: $pluginsGPath');
      wrote++;
    } else {
      ctx.output.info('Skipped (exists): $pluginsGPath');
      skipped++;
    }

    // 3a. Auto-trigger `plugins:refresh` when `.dowel/plugins.json` is
    //     present at run time. Reuses the canonical codegen path so the
    //     emitted barrel stays byte-identical to a manual
    //     `dart run dowel plugins:refresh` invocation.
    final pluginsJsonPath = p.join(root, '.dowel', 'plugins.json');
    if (File(pluginsJsonPath).existsSync()) {
      final exitCode =
          await PluginsRefreshCommand(projectRoot: root).handle(ctx);
      if (exitCode != 0) {
        ctx.output.error(
          'install: auto-chained plugins:refresh failed (exit $exitCode). '
          'Re-run `plugins:refresh` after fixing the underlying issue.',
        );
        return exitCode;
      }
    }

    // 4. lib/app/commands/_index.g.dart — initial empty consumer command
    //    list. Regenerated by `commands:refresh` / `make:command`.
    final indexPath = p.join(root, 'lib', 'app', 'commands', '_index.g.dart');
    if (_shouldWrite(indexPath, force)) {
      final raw = StubLoader.load('consumer_commands_index_initial.dart');
      FileHelper.writeFile(indexPath, raw);
      ctx.output.success('Created: $indexPath');
      wrote++;
    } else {
      ctx.output.info('Skipped (exists): $indexPath');
      skipped++;
    }

    // 5. pubspec dep injection. The codegen barrels at phases 3 + 4 import
    //    from `package:dowel/dowel.dart`; without a direct dep
    //    in the consumer pubspec the analyzer flags every barrel with
    //    `depend_on_referenced_packages`. A dowel entry the project already
    //    has (usually the caret `dart pub add dowel` wrote) is left as it is.
    //    Otherwise, two routing modes:
    //    a. monorepo / path-dep workflow: read .dart_tool/package_config.json,
    //       find the dowel rootUri, inject as a path dep so the consumer
    //       pubspec resolves the same dowel checkout that already powers
    //       the in-flight `dart run dowel` invocation.
    //    b. pub.dev workflow (no package_config or dowel resolved from a
    //       pub-cache absolute URI): a caret on the running version.
    final pubspecPath = p.join(root, 'pubspec.yaml');
    _addDowelDependency(pubspecPath, root: root);

    ctx.output.info(
      'Install scaffold complete ($wrote written, $skipped skipped). '
      'Chaining make:fast-cli for bin/dowel setup.',
    );

    // 6. Auto-chain make:fast-cli IN-PROCESS so a single `install` invocation
    //    yields the full canonical state (dispatcher + barrels + pubspec dep
    //    + bin/dowel + AOT bundle). Process-spawning here would lose stdout
    //    sharing + cost ~3s startup; the static entry preserves both.
    final fastCliExitCode = await MakeFastCliCommand.scaffoldInto(
      root: root,
      force: force,
      ctx: ctx,
    );
    if (fastCliExitCode != 0) {
      ctx.output.error(
        'install: auto-chained make:fast-cli failed (exit $fastCliExitCode). '
        'Re-run `make:fast-cli --force` after fixing the underlying issue.',
      );
      return fastCliExitCode;
    }

    return 0;
  }

  /// Adds `dowel` to the pubspec at [pubspecPath] unless either dependency
  /// section already declares it, in which case the user's constraint stays.
  static void _addDowelDependency(String pubspecPath, {required String root}) {
    final declared = pubspecDeclaresDependency(pubspecPath, 'dowel') ||
        pubspecDeclaresDependency(
          pubspecPath,
          'dowel',
          section: 'dev_dependencies',
        );
    if (declared) return;

    final relativeDowel = _resolveDowelRelativePath(root);
    if (relativeDowel != null) {
      ConfigEditor.addPathDependencyToPubspec(
        pubspecPath: pubspecPath,
        name: 'dowel',
        path: relativeDowel,
      );
      return;
    }

    ConfigEditor.addDependencyToPubspec(
      pubspecPath: pubspecPath,
      name: 'dowel',
      version: '^$dowelVersion',
    );
  }

  /// Returns true when [path] does not exist OR [force] is set.
  static bool _shouldWrite(String path, bool force) {
    if (force) return true;
    return !File(path).existsSync();
  }

  /// Extracts the package name from `<root>/pubspec.yaml`. Returns null
  /// when the file is missing or has no `name:` line.
  ///
  /// Extraction to a shared helper deferred per the extract-when-third-caller
  /// rule.
  static String? _readConsumerName(String root) {
    final pubspec = File(p.join(root, 'pubspec.yaml'));
    if (!pubspec.existsSync()) return null;
    final match = RegExp(
      r'^name:\s*(\S+)',
      multiLine: true,
    ).firstMatch(pubspec.readAsStringSync());
    return match?.group(1);
  }

  /// Resolves the on-disk path to `dowel` relative to the
  /// consumer's pubspec.yaml location. Reads
  /// `<consumerRoot>/.dart_tool/package_config.json`, locates the
  /// `dowel` entry, and rebases its `rootUri` (relative to
  /// `.dart_tool/`) onto [consumerRoot]. Returns null when the file is
  /// missing, malformed, or when dowel resolves to a pub-cache location
  /// (in which case the caller falls back to a version-constraint dep).
  ///
  /// See `_readConsumerName` extraction rationale above.
  static String? _resolveDowelRelativePath(String consumerRoot) {
    final configFile = File(
      p.join(consumerRoot, '.dart_tool', 'package_config.json'),
    );
    if (!configFile.existsSync()) return null;

    final Object? decoded;
    try {
      decoded = jsonDecode(configFile.readAsStringSync());
    } catch (_) {
      return null;
    }
    if (decoded is! Map<String, dynamic>) return null;
    final packages = decoded['packages'];
    if (packages is! List) return null;

    for (final entry in packages) {
      if (entry is! Map) continue;
      if (entry['name'] != 'dowel') continue;
      final rootUri = entry['rootUri'];
      if (rootUri is! String) return null;
      // Pub-cache resolutions are absolute `file:` URIs; only path-dep
      // workflows yield a relative rootUri suitable for a path: dep.
      final Uri reference;
      try {
        reference = Uri.parse(rootUri);
      } on FormatException {
        return null;
      }
      if (reference.hasScheme || p.isAbsolute(rootUri)) return null;
      // rootUri is a URI reference relative to .dart_tool/, percent-encoded
      // and with or without a trailing slash. Resolving it as a URI decodes
      // it; joining it as a path wrote `plug%20x` for `plug x`.
      final absolute = p.normalize(
        configFile.parent.absolute.uri.resolveUri(reference).toFilePath(),
      );
      return p.relative(absolute, from: consumerRoot);
    }
    return null;
  }
}
